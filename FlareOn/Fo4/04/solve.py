# 修改版Windows XP记事本，入口点被patch，先执行恶意代码再跳回原始入口。
# 恶意代码遍历 %USERPROFILE%\flareon2016challenge\ 目录下的PE文件，
# 按PE时间戳链式匹配4个阶段，每阶段从PE文件特定偏移读取8字节写入key.bin。
# 最终阶段用key.bin的32字节与硬编码密文XOR得到flag。
#
# 关键线索：目录名"flareon2016challenge"指向FlareOn 3 (2016)的挑战文件。
# 4个匹配的时间戳：0x57d1b2a2, 0x57d2b0f8, 0x49180192, 0x579e9100
#
# 加密数据在函数0x10146c0中，XOR解密在函数0x1014670。

enc = bytes([
    0x37, 0xe7, 0xd8, 0xbe, 0x7a, 0x53, 0x30, 0x25,
    0xbb, 0x38, 0x57, 0x26, 0x97, 0x26, 0x6f, 0x50,
    0xf4, 0x75, 0x67, 0xbf, 0xb0, 0xef, 0xa5, 0x7a,
    0x65, 0xae, 0xab, 0x66, 0x73, 0xa0, 0xa3, 0xa1,
])

# key.bin: 来自FlareOn 2016挑战PE文件偏移0x400/0x410/0x420/0x430处的代码字节
key = bytes([
    0x55, 0x8b, 0xec, 0x8b, 0x4d, 0x0c, 0x56, 0x57,
    0x8b, 0x55, 0x08, 0x52, 0xff, 0x15, 0x30, 0x20,
    0xc0, 0x40, 0x50, 0xff, 0xd6, 0x83, 0xc4, 0x08,
    0x00, 0x83, 0xc4, 0x08, 0x5d, 0xc3, 0xcc, 0xcc,
])

flag = bytes(e ^ k for e, k in zip(enc, key)).decode('ascii')
print(f'Flag: {flag}')
